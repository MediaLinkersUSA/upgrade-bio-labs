/**
 * Builds the returning-customer blocklist from the old store's export.
 *
 * Input : a newline-separated list of email addresses
 * Output: src/lib/legacy-customers.ts
 *
 * Run: node scripts/build-legacy-blocklist.mjs <emails.txt>
 *
 * TWO THINGS MATTER HERE.
 *
 * Privacy. This is the client's real customer list. It is stored as SHA-256
 * hashes of the normalised address, never plaintext, and the module that reads
 * it is server-only - it must never reach the browser bundle, or the file
 * becomes a downloadable customer list for anyone who views source.
 *
 * Normalisation. A blocklist keyed on the raw string is trivially defeated:
 * john@gmail.com, John@Gmail.com, j.o.hn@gmail.com and john+new@gmail.com are
 * one inbox and one customer. Gmail ignores dots and everything after a plus,
 * so those are stripped before hashing, and the same function runs at checkout.
 */
import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";

const IN = process.argv[2];
if (!IN) {
  console.error("usage: node scripts/build-legacy-blocklist.mjs <emails.txt>");
  process.exit(1);
}

const OUT = path.join(process.cwd(), "src", "lib", "legacy-customers.ts");

/** Providers that ignore dots in the local part. */
const DOT_INSENSITIVE = new Set(["gmail.com", "googlemail.com"]);

export function normalizeEmail(raw) {
  const email = String(raw ?? "").trim().toLowerCase();
  const at = email.lastIndexOf("@");
  if (at < 1) return "";
  let local = email.slice(0, at);
  const domain = email.slice(at + 1);

  // Sub-addressing: everything from the first plus is a label, not an identity.
  const plus = local.indexOf("+");
  if (plus > 0) local = local.slice(0, plus);
  if (DOT_INSENSITIVE.has(domain)) local = local.replaceAll(".", "");

  return local && domain ? `${local}@${domain}` : "";
}

const hash = (s) => createHash("sha256").update(s).digest("hex").slice(0, 32);

/** Obvious placeholders from the old admin, not real customers. */
const JUNK = /@(mailinator|example|test)\.com$|^(test|dummy|fuke|kimobafo)/i;

const raw = fs.readFileSync(IN, "utf8").split(/\r?\n/);
const normalized = new Set();
let skipped = 0;

for (const line of raw) {
  const e = line.trim();
  if (!e || !e.includes("@")) continue;
  if (JUNK.test(e)) {
    skipped++;
    continue;
  }
  const n = normalizeEmail(e);
  if (n) normalized.add(n);
}

const hashes = [...normalized].map(hash).sort();

const file = `// GENERATED by scripts/build-legacy-blocklist.mjs - do not edit by hand.
//
// SHA-256 (truncated to 128 bits) of normalised email addresses for customers
// who already bought from the previous storefront. They are excluded from the
// first-order promotion.
//
// Hashed, not plaintext: this is the client's customer list and it must not be
// readable in the repo. SERVER ONLY - importing this into a client component
// would ship the whole list to every visitor's browser.
//
// ${normalized.size} customers, generated from the store export.

export const LEGACY_CUSTOMER_HASHES: ReadonlySet<string> = new Set([
${hashes.map((h) => `  "${h}",`).join("\n")}
]);
`;

fs.writeFileSync(OUT, file);
console.log(`${raw.length} lines in`);
console.log(`${skipped} test/placeholder addresses skipped`);
console.log(`${normalized.size} unique customers -> ${hashes.length} hashes`);
console.log(`written to ${path.relative(process.cwd(), OUT)}`);
